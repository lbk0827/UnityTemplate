# Gate mines touch both a dense lower shell and the free internal flight space.
MINES = {14: [(5, 8)], 15: [(3, 7)], 16: [(5, 7)], 17: [(5, 8), (3, 5)],
         18: [(5, 8)], 19: [(3, 8)], 20: [(5, 8), (7, 5)]}


def opening(stage, template):
    intent, art = BOARDS[stage - 1]
    rows = [list('.' * 11)] + [list(row) for row in art]
    height = min(16, max(14, len(rows) + 2))
    rows += [list('.' * 11) for _ in range(height - len(rows))]
    specs = []
    for x, y in MINES.get(stage, []):
        y += 1  # authored art has one row of top air
        assert rows[y][x] != '.', (stage, x, y)
        rows[y][x] = '.'
        specs.append(dict(type='mine', col=x, row=y))
    assert all(len(row) == 11 for row in rows), stage
    assert sum(c != '.' for row in rows for c in row) >= 40, stage
    template.update(title=TITLES[stage-1]+' · 1', intent=intent, gridRows=height, rows=[''.join(row) for row in rows],
                    gimmicks=specs, balls=sum(c != '.' for row in rows for c in row) + 12)
    return template
